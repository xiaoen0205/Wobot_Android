import 'dart:convert';
import 'dart:io';

/// Creates fake Firebase configuration for checks and debug build smoke tests.
/// Run from app/. It cannot authenticate and must not replace real configuration.
void main() {
  if (!File('pubspec.yaml').existsSync() ||
      !Directory('android/app').existsSync()) {
    stderr.writeln('Run this command from the app directory.');
    exitCode = 1;
    return;
  }
  final options = File('lib/firebase_options.dart');
  final android = File('android/app/google-services.json');
  if (options.existsSync() || android.existsSync()) {
    stderr.writeln(
      'Firebase configuration already exists; refusing to replace it.',
    );
    exitCode = 1;
    return;
  }

  options.writeAsStringSync('''
// CI PLACEHOLDER: generated by tool/prepare_ci.dart; cannot sign in.
import 'package:firebase_core/firebase_core.dart';

class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform => const FirebaseOptions(
    apiKey: 'ci-placeholder-not-a-real-key',
    appId: '1:123456789012:android:0123456789abcdef012345',
    messagingSenderId: '123456789012',
    projectId: 'wobot-ci-placeholder',
  );
}
''');
  android.writeAsStringSync(
    const JsonEncoder.withIndent('  ').convert({
      'project_info': {
        'project_number': '123456789012',
        'project_id': 'wobot-ci-placeholder',
      },
      'client': [
        {
          'client_info': {
            'mobilesdk_app_id': '1:123456789012:android:0123456789abcdef012345',
            'android_client_info': {'package_name': 'com.xiaoen0205.wobot'},
          },
          'oauth_client': [
            {
              'client_id':
                  '123456789012-ci-placeholder.apps.googleusercontent.com',
              'client_type': 3,
            },
          ],
          'api_key': [
            {'current_key': 'ci-placeholder-not-a-real-key'},
          ],
        },
      ],
      'configuration_version': '1',
    }),
  );
  stdout.writeln('Created CI placeholders. Google sign-in is not configured.');
}
